// Checks the integrated portal and embedded real GLB; remote services are blocked.
const {chromium}=require(process.env.WOS_PLAYWRIGHT_MODULE||'playwright');
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const base=process.env.WOS_PORTAL_TEST_URL||'http://127.0.0.1:8798/DeS-Portal/';
const out=process.env.WOS_KARURO_TEST_OUTPUT||path.resolve(__dirname,'../../witch-3d-studio/renders');
async function run(){
 const browser=await chromium.launch({channel:'chrome',headless:true});
 const results=[];
 try{
  for(const [label,width,height] of [['desktop',1440,1000],['mobile',390,844]]){
   const context=await browser.newContext({viewport:{width,height},isMobile:width<600,hasTouch:width<600});
   const errors=[],modelRequests=[];
   await context.route('**/*',route=>route.request().url().startsWith(base)?route.continue():route.abort());
   const page=await context.newPage();page.on('pageerror',e=>errors.push(e.message));
   page.on('request',request=>{if(request.url().endsWith('.glb'))modelRequests.push(request.url());});
   await page.goto(base+'?preview=1#notes');
   await page.locator('#view-notes').waitFor({state:'visible'});
   const order=await page.locator('#navigation [data-nav]').evaluateAll(nodes=>nodes.map(n=>({id:n.dataset.nav,label:n.textContent})));
   const notes=order.findIndex(n=>n.id==='notes');assert.equal(order[notes+1].id,'karuro');assert.ok(order[notes+1].label.includes('禁断のかるろ'));
   assert.equal(modelRequests.length,0,'Other menus must not download the 63MB model');
   if(width<600)await page.locator('#menu-toggle').click();
   await page.locator('#navigation [data-nav=karuro]').click();
   await page.locator('#view-karuro').waitFor({state:'visible'});
   const iframe=await page.locator('#view-karuro iframe').elementHandle(),frame=await iframe.contentFrame();
   await frame.waitForFunction(()=>window.witchViewer?.ready,{},{timeout:60000});
   assert.ok(frame.url().startsWith(base+'apps/karuro/'));
   assert.equal(await frame.locator('#error').isHidden(),true);
   const stats=await frame.evaluate(()=>({triangles:witchViewer.triangles,materials:witchViewer.materials,style:witchViewer.renderStyle}));
   assert.equal(stats.triangles,1884666);assert.equal(stats.style,'original-meshy-pbr');
   assert.ok(stats.materials.every(m=>m.baseColor&&m.normal&&m.roughness&&m.metalness));
   assert.equal(await frame.locator('#wire').count(),0);assert.equal(await frame.locator('.masthead').count(),0);
   assert.equal(await frame.locator('.title-block .eyebrow').innerText(),'01 — halloween witch かるろ');
   await frame.locator('[data-view=back]').click();await frame.locator('[data-view=front]').click();
   await frame.locator('[data-focus=face]').click();await frame.locator('#reset').click();
   await frame.locator('#zoom-in').click();await frame.locator('#auto').click();
   await frame.locator('#reference').click();assert.equal(await frame.locator('#reference-dialog').evaluate(n=>n.open),true);await frame.locator('#reference-close').click();
   await frame.locator('#auto').click();
   await frame.locator('#reset').click();
   await page.screenshot({path:path.join(out,`portal-karuro-${label}.png`)});
   assert.equal(modelRequests.length,1,'The second model is not loaded until selected');
   await frame.locator('#next-model').click();
   await frame.waitForFunction(()=>witchViewer.ready&&witchViewer.modelId==='reporter');
   assert.equal(await frame.locator('.title-block .eyebrow').innerText(),'02 — かるろ');
   assert.equal(await frame.locator('#title').innerText(),'かるろ');
   assert.equal(await frame.evaluate(()=>witchViewer.triangles),356950);
   assert.equal(await frame.locator('[data-focus=hat]').isHidden(),true);
   assert.equal(await frame.locator('[data-focus=staff]').innerText(),'マイク');
   await frame.locator('#reference').click();
   await frame.waitForFunction(()=>{const img=document.getElementById('reference-image');return img.complete&&img.naturalWidth>=1200;});
   assert.ok((await frame.locator('#reference-image').getAttribute('src')).endsWith('reporter-character-sheet.png'));
   await page.screenshot({path:path.join(out,`portal-karuro-sheet-${label}.png`)});
   await frame.locator('#reference-close').click();
   await page.screenshot({path:path.join(out,`portal-karuro-reporter-${label}.png`)});
   await frame.locator('#previous-model').click();
   await frame.waitForFunction(()=>witchViewer.ready&&witchViewer.modelId==='witch');
   assert.equal(await frame.locator('[data-focus=hat]').isHidden(),false);
   assert.equal(await frame.locator('[data-focus=staff]').innerText(),'杖の束');
   await frame.locator('#next-model').click();
   await frame.waitForFunction(()=>witchViewer.ready&&witchViewer.modelId==='reporter');
   await frame.locator('#next-model').click();
   await frame.waitForFunction(()=>witchViewer.ready&&witchViewer.modelId==='penguin');
   assert.equal(await frame.locator('.title-block .eyebrow').innerText(),'03 — でんぴー');
   assert.equal(await frame.locator('#title').innerText(),'でんぴー');
   assert.equal(await frame.evaluate(()=>witchViewer.triangles),173760);
   assert.ok((await frame.evaluate(()=>witchViewer.materials)).every(m=>m.baseColor&&m.normal&&m.roughness&&m.metalness));
   assert.equal(await frame.locator('[data-focus=staff]').isHidden(),true);
   assert.equal(await frame.locator('[data-focus=hat]').isHidden(),true);
   assert.equal(await frame.locator('[data-focus=outfit]').innerText(),'お腹');
   await page.screenshot({path:path.join(out,`portal-karuro-penguin-${label}.png`)});
   await frame.locator('[data-focus=face]').click();
   await page.screenshot({path:path.join(out,`portal-karuro-penguin-face-${label}.png`)});
   await frame.locator('#reset').click();
   await frame.locator('#reference').click();
   await frame.waitForFunction(()=>{const img=document.getElementById('reference-image');return img.complete&&img.naturalWidth>=1200;});
   assert.ok((await frame.locator('#reference-image').getAttribute('src')).endsWith('penguin-character-sheet.png'));
   await page.screenshot({path:path.join(out,`portal-karuro-penguin-sheet-${label}.png`)});
   await frame.locator('#reference-close').click();
   await frame.locator('#next-model').click();
   await frame.waitForFunction(()=>witchViewer.ready&&witchViewer.modelId==='witch');
   assert.equal(await frame.locator('[data-focus=outfit]').innerText(),'衣装');
   await frame.locator('#previous-model').click();
   await frame.waitForFunction(()=>witchViewer.ready&&witchViewer.modelId==='penguin');
   await frame.locator('#previous-model').click();
   await frame.waitForFunction(()=>witchViewer.ready&&witchViewer.modelId==='reporter');
   assert.equal(await frame.locator('[data-focus=staff]').innerText(),'マイク');
   await frame.locator('#next-model').click();
   await frame.waitForFunction(()=>witchViewer.ready&&witchViewer.modelId==='penguin');
   await page.evaluate(()=>location.hash='notes');
   await frame.waitForFunction(()=>!witchViewer.panelActive&&!witchViewer.rendering);
   await page.evaluate(()=>location.hash='karuro');
   await frame.waitForFunction(()=>witchViewer.panelActive&&witchViewer.rendering);
   assert.equal(await page.locator('#view-karuro iframe').count(),1);
   assert.equal(modelRequests.length,3,'Switching models and menus should reuse all three loaded models');
   assert.equal(await frame.evaluate(()=>witchViewer.modelId),'penguin');
   assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),true);
   assert.equal(await frame.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),true);
   assert.deepEqual(errors,[]);
   results.push({label,models:3,menuAfterNotes:true,lazyModels:true,oneDownloadPerModel:true,modelTitles:true,modelSheet:true,penguinFocusLabels:true,resumesAfterNavigation:true,...stats});
   console.log('PASS '+label+': all three models, arrow wraparound, model titles/sheets, lazy GLB/cache, pause/resume');
   await context.close();
  }
  const recoveryContext=await browser.newContext({viewport:{width:1200,height:900}});
  const recovery=await recoveryContext.newPage(),recoveryErrors=[];
  recovery.on('pageerror',error=>recoveryErrors.push(error.message));
  let rejectReporter=true;
  await recoveryContext.route('**/*',async route=>{
   const url=route.request().url();
   if(!url.startsWith(base))return route.abort();
   if(url.endsWith('meshy-reporter.glb')&&rejectReporter)return route.fulfill({status:404,body:'not found'});
   return route.continue();
  });
  await recovery.goto(base+'apps/karuro/index.html?preview=1');
  await recovery.waitForFunction(()=>window.witchViewer?.ready,{},{timeout:60000});
  await recovery.locator('#next-model').click();await recovery.locator('#error').waitFor({state:'visible'});
  assert.match(await recovery.locator('#error-message').innerText(),/HTTP 404/);
  await recovery.locator('#previous-model').click();
  await recovery.waitForFunction(()=>witchViewer.ready&&witchViewer.modelId==='witch');
  await recovery.locator('#next-model').click();await recovery.locator('#error').waitFor({state:'visible'});
  rejectReporter=false;await recovery.locator('#retry').click();
  await recovery.waitForFunction(()=>witchViewer.ready&&witchViewer.modelId==='reporter',{},{timeout:60000});
  assert.deepEqual(recoveryErrors,[]);await recoveryContext.close();
  const raceContext=await browser.newContext({viewport:{width:1200,height:900}});
  const race=await raceContext.newPage(),raceErrors=[];
  race.on('pageerror',error=>raceErrors.push(error.message));
  await raceContext.route('**/*',async route=>{
   if(!route.request().url().startsWith(base))return route.abort();
   if(route.request().url().endsWith('meshy-witch.glb'))await new Promise(resolve=>setTimeout(resolve,1000));
   try{await route.continue();}catch(error){if(!/closed|cancel|abort/i.test(error.message))throw error;}
  });
  await race.goto(base+'apps/karuro/index.html?preview=1');
  await race.waitForFunction(()=>window.witchViewer);
  await race.evaluate(()=>{document.getElementById('next-model').click();document.getElementById('previous-model').click();document.getElementById('next-model').click();});
  await race.waitForFunction(()=>witchViewer.ready&&witchViewer.modelId==='reporter',{},{timeout:60000});
  await race.waitForTimeout(1200);
  assert.equal(await race.evaluate(()=>witchViewer.modelId),'reporter');
  assert.equal(await race.locator('#title').innerText(),'かるろ');assert.deepEqual(raceErrors,[]);
  await raceContext.close();
  results.push({failedDownloadRecovery:true,retryCurrentModel:true,rapidSwitchCancellation:true});
  console.log('PASS model failure recovery, retry, and rapid switching during download');
  fs.writeFileSync(path.join(out,'portal-karuro-test-report.json'),JSON.stringify(results,null,2));
 }finally{await browser.close();}
}
run().catch(error=>{console.error(error);process.exitCode=1});
