/* もふもふ冒険 つないだステージ E「かぜのり群島」＝ ステージ 9「そよかぜ浮島」→ つなぎ「みずうみの岩」→ ステージ 10「くもまの見はらし港」。
   つなぎ方は adventure-join.js。後半（見はらし港）は北へ 89m ずらす（港の広場は z 74〜104）。
   つなぎ：浮島の北の島（前半のゴールだった所。入口のセーブ地点）の北に、みずうみ（x -6〜6・z 34〜52）。その向こうに岩（z 52〜60）。
     帆のいかだ（北の島の北の縁につけてある）で岩へ渡り（せんぷうき箱を南の縁に置く）、岩のふうせんで上がると、高い所の風（いつも北へ吹く）で、港の広場の上へ流れる。
     いかだとふうせんの 2 つを続けて使う。北の島から岩は 18m、岩から港の広場は 14m（4 人で積んで投げても、せんぷうき箱の風でも届かない。高い所の風は 9m から上：せんぷうき箱で浮いて仲間を投げても入らない）。
     ふうせんは 2 人では重くて上がらない：1 人ずつ渡る（放したふうせんは岩へ戻る。いかだは、だれも乗らないまま 8 秒で北の島へ戻る）。
   変えたら `node tools/lint-adventure.mjs e` と `node tools/test-adventure.mjs e`（前半 s9.mjs・つなぎ e.mjs・後半 s10.mjs を続けて動かす）で確かめる */
import s9 from './s9.js?v=4.24';
import s10 from './s10.js?v=4.24';
import { join } from '../adventure-join.js?v=4.24';

export default kit => join(kit, {
  name: 'かぜのり群島', first: ['s9', s9], second: ['s10', s10], off: [0, 89],
  // つなぎの中身。座標はステージ全体のもの、番号はつなぎの中だけで数える
  link: ({ B, CP, water, raft, fan, balloon, gust }) => {
    const lake = water(0, 43, 12, 18, -0.25, -4);                                     // みずうみ（水面 -0.25）
    return {
      boxes: [B(0, 0, 56, 10, 8, 1, 1)],                                              // 0 岩（x -5〜5・z 52〜60）
      movers: [lake, raft(lake, 0, 35.6)],                                            // 0 みずうみ・1 いかだ（北の島の北の縁につけてある）
      crates: [fan(0, 0, 35.6)],                                                      // 0 いかだのせんぷうき箱（まん中）
      ropes: [balloon(0, 1.9, 57.5, 10, 1.2)],                                        // 0 岩のふうせん
      // 岩の上の高い所の風（z 57〜80・高さ 9m から。港の広場の上で風から出て止まる）。せんぷうき箱で浮いて投げられた仲間（てっぺん 8.4m）は入らない
      winds: [gust(0, 68.5, 4, 23, 9, 16, [0, 3])],
      // 入口のセーブ地点は、北の島をほぼ全部ふくむ（北の橋から入ると、すぐふれる）。岩のセーブ地点は、風の南（空から落ちてくる間に、風で北の縁へ流されない）
      cps: [CP(0, 0, 30, 'そよかぜ浮島 → くもまの見はらし港：いかだで岩へ渡り、ふうせんで風にのろう', 4.5), CP(0, 0, 53.5, 'ふうせんにつかまって、風で北の港へ')],
      deco: [{ beacon: [4.5, 0, 59.5], color: '#ffd84a' }],
    };
  },
});
