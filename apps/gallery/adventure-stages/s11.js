/* もふもふ冒険 ステージ 11「みなとの工事場」（つないだステージ F の前半。クレーン・鉄球・水門を、1 つずつ教える）。
   夕方の港の工事場。まん中の広場（スタート）から、西のクレーン・東の解体小屋・南の水門へ分かれる。ゴールは、北の 14m 先の桟橋。
   桟橋への橋は、広場の北の縁のソケット 3 つに、でんちが入っている間だけあがる（13m 下に止めておく。橋のたもとのランプが 3 つ光る）。でんちは、3 つの場所に 1 つずつ。
   西：沖の台（広場から 14m）の上のでんちを、クレーンで運ぶ。レバーは 3 本（左右・前後・上げ下げ。つまみは、動かす部分と同じ色）。
       左右・前後で、フックをでんちの真上へ → 上げ下げを奥まで倒すと、下りて爪が開く → 戻すと閉じて吊る → 左右を戻して広場の上へ → また倒すと放す。
   東：解体小屋の戸口は板張り。戸の前に鉄球が下がっている。西へ引いて放すと、ふれて板を割る（引きが弱いと、はね返されて割れない）。中にでんち。
   南：水門の水路（14m）の向こうの島に、でんち。ふだんの水面は岸の 9m 下で、浮かぶ木箱 5 つも、ずっと下にある。ハンドルを回すと水面が上がり、木箱が岸と同じ高さの飛び石になる。
       島にもハンドルがある（水が引いたあとの帰り道）。でんちを持って、飛び石を戻る。
   人ではできないこと：橋のソケットは、でんちだけが押せる。沖の台・水門の島・桟橋は、どこからも 14m（4 人で積んで投げても 11m まで）。小屋の壁は 14m。板張りは重い箱しか割れない
   （このステージの重い箱は、鉄球と水路の木箱だけ。木箱は水路から出られない）。クレーンのフックに仲間が乗っても、行けるのは沖の台（行き止まり）だけ。
   足場や仕掛けの作り方（B・P・CP など）は adventure-world.js の kit を受け取って使う。座標は m、x が東、z が北、y が高さ。
   変えたら `node tools/lint-adventure.mjs 11` と `node tools/test-adventure.mjs 11` で、自動操縦（tools/adventure-bots/s11.mjs）が 1 人で最後まで解けることを確かめる */
export default ({ B, CP, socket, cell, lever, planks, crane, ironball, water }) => {
  const H = 14;                                                                       // 壁の高さ
  const wx = (x0, x1, z, top = H, bottom = 0) => B((x0 + x1) / 2, top, z, x1 - x0, 0.6, top - bottom, 1);   // 東西にのびる壁（z の線の上）
  const wz = (z0, z1, x, top = H, bottom = 0) => B(x, top, (z0 + z1) / 2, 0.6, z1 - z0, top - bottom, 1);   // 南北にのびる壁（x の線の上）
  // 水路の飛び石（1.4m の木箱 5 つ）のまん中の z：岸（z -10）から島（z -24）までの 14m を、すき間 7/6m でならべる
  const gap = 7 / 6, stones = [0, 1, 2, 3, 4].map(k => -10 - gap - 0.7 - k * (1.4 + gap));
  return { name: 'みなとの工事場', sky: ['#2c4a6e', '#ffb07a'], kill: -12,
    boxes: [
      // 床：広場（x -12〜12、z -10〜10）・沖の台（西に 14m）・解体小屋（東）・水門の島（南に 14m）・桟橋（北に 14m）
      B(0, 0, 0, 24, 20, 1, 1), B(-29, 0, 0, 6, 6, 1, 1), B(17.65, 0, 0, 11.3, 10.6, 1, 2), B(0, 0, -29, 8, 10, 1, 1), B(0, 0, 28, 10, 8, 1, 0),
      // 解体小屋の壁。西の戸口（z -1.5〜1.5）は板張り。戸口の上は 3.5m から壁
      wz(-5.3, -1.5, 14), wz(1.5, 5.3, 14), wz(-1.5, 1.5, 14, H, 3.5), planks(wz(-1.5, 1.5, 14, 3.5)),
      wx(14, 23.3, -5), wx(14, 23.3, 5), wz(-5.3, 5.3, 23),
      // 飛び石の杭（水の底のほう。木箱の元の場所）
      ...stones.map(z => B(0, -10.5, z, 1, 1, 1, 1))],
    plates: [socket(-4, 0, 7), socket(0, 0, 7), socket(4, 0, 7)],
    movers: [
      { b: B(0, -13, 17, 3, 14, 0.5, 4), to: [0, 13, 0], mode: 'hold', on: [0, 1, 2], lamps: true, speed: 6 },   // 0 桟橋への橋（13m 下に止めておく）
      water(0, -17, 3, 14, -9, -11.5, { rise: 8.3, handles: [0, 1], up: 5, hold: 20, down: 8 })],              // 1 水門の水路（水面 -9 → -0.7）
    handles: [{ x: 2.4, y: 0, z: -9 }, { x: 2.4, y: 0, z: -25 }],                     // 水門のハンドル（広場・島）
    crates: [lever(-10, 0, -4, 'x'), lever(-10, 0, -6, 'x'), lever(-10, 0, -8, 'x'),  // 0 クレーンの左右・1 前後・2 上げ下げ
      cell(-29, 0, 2),                                                                // 3 沖の台のでんち
      ironball(13.1, 0, 0, 'x', 2, 3),                                                // 4 解体小屋の鉄球（板張りの 0.1m 西。西へ 2m まで引ける）
      cell(19, 0, 0),                                                                 // 5 小屋の中のでんち
      cell(0, 0, -30),                                                                // 6 水門の島のでんち
      ...stones.map(z => ({ x: 0, y: -10.5, z, s: 1.4, heavy: true }))],              // 7〜11 飛び石の木箱
    // クレーン：左右 x -7（広場）〜 -29（沖の台）、前後 z -2〜2、フックの底 4m〜1.4m
    cranes: [crane([0, -7, -29], [1, -2, 2], [2, 4, 1.4])],
    cps: [CP(3, 0, -3, 'でんちを3つ、北の縁のソケットへ。橋があがる'),
      CP(-6, 0, -7, 'レバーでクレーンを動かそう。奥まで倒すとフックが下りて開き、戻すと閉じて吊る'),
      CP(19, 0, -2.5, 'でんちを持って広場へ'),
      CP(0, 0, -29, '島のハンドルを回すと、水が上がって飛び石ができる')],
    goal: { x: 0, y: 0, z: 29 },
    objective: { label: 'でんち', on: [0, 1, 2], need: 3 },
    deco: [{ beacon: [-31, 0, -2], color: '#c05cff' }, { beacon: [21.5, 0, -3.5], color: '#ff9f43' }, { beacon: [-3, 0, -32], color: '#4fc3ff' }, { beacon: [3.5, 0, 30.5], color: '#7ee0a0' }] };
};
