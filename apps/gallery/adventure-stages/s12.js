/* もふもふ冒険 ステージ 12「しおかぜ灯台」（つないだステージ F の後半。前半で覚えた水門・鉄球・クレーンを、ひとひねりして使い、ジップラインと組み合わせる）。
   夜明けの港。まん中の岸壁（スタート）から、西の井戸の庭・北の海ぞいへ。ゴールは、北の 16m 先の灯台の島（灯台の庭の戸は、島のソケットにでんちがある間だけあく）。
   西（水門のひねり）：でんちは、深い井戸（10m）の底。人は、井戸のあみで出入りできるが、でんちを持っては登れない。ハンドルで井戸に水を満たすと、でんちが浮いて上がってくる。
   北（鉄球のひねり）：島へのジップラインのとっての先は、板張りの窓でふさいである（板に当たって、とってが進まない）。窓の前の鉄球は、南を板のつっかい（くさび）でふさがれて引けない。
       となりの鉄球（東西にふれる）を西へ引いて放し、くさびを割る → 窓の前の鉄球を南へ引いて放し、窓を割る。
   ジップライン（新しい使い方）：つかまっている間は手がふさがるので、でんちは運べない。でんちは、岸壁のソケット（荷台）に置いておき、島に渡ってから、島のクレーンのレバーで吊って運ぶ。
       島には、岸壁へ戻るジップラインもある（でんちを置き忘れて渡っても、戻れる）。
   人ではできないこと：島は岸壁から 16m（4 人で積んで投げても 11m まで）。クレーンのレバーは島にしかない（だれかが島に渡るまで、フックは動かない）。
   灯台の庭の壁は 14m。くさびと窓の板張りは重い箱でしか割れない（このステージの重い箱は鉄球 2 つだけ。押しつけても割れない）。
   足場や仕掛けの作り方（B・P・CP など）は adventure-world.js の kit を受け取って使う。座標は m、x が東、z が北、y が高さ。
   変えたら `node tools/lint-adventure.mjs 12` と `node tools/test-adventure.mjs 12` で、自動操縦（tools/adventure-bots/s12.mjs）が 1 人で最後まで解けることを確かめる */
export default ({ B, CP, socket, cell, lever, planks, net, crane, ironball, water, zip }) => {
  const H = 14;                                                                       // 壁の高さ
  const wx = (x0, x1, z, top = H, bottom = 0) => B((x0 + x1) / 2, top, z, x1 - x0, 0.6, top - bottom, 1);   // 東西にのびる壁（z の線の上）
  const wz = (z0, z1, x, top = H, bottom = 0) => B(x, top, (z0 + z1) / 2, 0.6, z1 - z0, top - bottom, 1);   // 南北にのびる壁（x の線の上）
  return { name: 'しおかぜ灯台', sky: ['#24345e', '#f7c6a3'], kill: -12,
    boxes: [
      // 井戸のあみ（井戸の北の面。まわりの床より先に書く）
      net(B(-20, 0, 1.1, 2.4, 0.2, 10, 1), 's'),
      // 床：岸壁（x -12〜12、z -10〜10）・井戸の庭（西。まん中に 2.4m 四方・深さ 10m の井戸。まわりの床は井戸の底まで厚い）・灯台の島（北に 16m）
      B(0, 0, 0, 24, 20, 1, 1), B(-23.6, 0, 0, 4.8, 12, 11, 0), B(-15.4, 0, 0, 6.8, 12, 11, 0), B(-20, 0, -3.6, 2.4, 4.8, 11, 0), B(-20, 0, 3.6, 2.4, 4.8, 11, 0),
      B(-20, -10, 0, 2.4, 2.4, 1, 1), B(0, 0, 32, 16, 12, 1, 1),
      // 窓の前の鉄球のつっかい（くさび）と、ジップラインの窓の板
      planks(B(-1.2, 1.2, 8.55, 3.2, 0.6, 1.2)), planks(B(0.9, 3.5, 10.35, 4.2, 0.3, 3.5)),
      // 灯台の庭の壁。南の戸口（x -1.5〜1.5）の上は 3.5m から壁
      wx(-5, -1.5, 32), wx(1.5, 5, 32), wx(-1.5, 1.5, 32, H, 3.5), wz(32, 38, -5), wz(32, 38, 5), wx(-5, 5, 38)],
    plates: [socket(-6, 0, 4), socket(4, 0, 29)],                                     // 0 岸壁の荷台・1 島のソケット
    movers: [
      { b: B(0, 3.5, 32, 3, 0.4, 3.5, 4), to: [3.2, 0, 0], mode: 'hold', on: [1], lamps: true },   // 0 灯台の庭の戸（東の壁の中へ引く）
      water(-20, 0, 2.4, 2.4, -9.9, -10, { rise: 9.5, handles: [0], up: 5, hold: 14, down: 8 })],   // 1 井戸の水（水面 -9.9 → -0.4）
    handles: [{ x: -17, y: 0, z: -2.5 }],
    crates: [cell(-20, -10, -0.6),                                                    // 0 井戸の底のでんち
      ironball(-3.4, 0, 8.55, 'x', 2, 3),                                             // 1 くさびを割る鉄球（東西）
      ironball(-0.2, 0, 9.6, 'z', 2, 3),                                              // 2 窓の前の鉄球（南北。南はくさびで 0.25m しか引けない）
      lever(-6.5, 0, 27, 'x'), lever(-6.5, 0, 29, 'x'), lever(-6.5, 0, 31, 'x')],     // 3 クレーンの左右・4 前後・5 上げ下げ（島）
    // クレーン：はじめは島のソケットの上。左右 x 4〜-6、前後 z 29（島）〜4（岸壁の荷台）、フックの底 5m〜1.4m
    cranes: [crane([3, 4, -6], [4, 29, 4], [5, 5, 1.4])],
    ropes: [zip(2, 1.9, 9.85, [0, 0, 16.5]),                                          // 0 島へのジップライン（窓の板の向こうへ）
      zip(-4, 1.9, 26.15, [0, 0, -16.5])],                                            // 1 岸壁へ戻るジップライン
    cps: [CP(0, 0, -7, 'でんちを島へ。ジップラインでは荷物を運べない'),
      CP(-16, 0, -4, 'ハンドルで井戸に水を満たすと、でんちが浮いてくる'),
      CP(6, 0, 6, '東西の鉄球でくさびを割ってから、窓の前の鉄球を引こう'),
      CP(0, 0, 28.5, 'クレーンで、岸壁の荷台のでんちを島のソケットへ')],
    goal: { x: 0, y: 0, z: 36 },
    deco: [{ beacon: [-23, 0, -4], color: '#4fc3ff' }, { beacon: [-8.5, 0, 6], color: '#ffd84a' }, { beacon: [6.5, 0, 28], color: '#ffd84a' }, { beacon: [-2.5, 0, 36], color: '#7ee0a0' },
      B(-1.5, 4.5, 10.35, 0.6, 0.6, 4.5, 2), B(3.3, 4.5, 10.35, 0.6, 0.6, 4.5, 2), B(0.9, 5, 10.35, 5.4, 0.6, 0.5, 2)] };   // 窓の枠（見た目だけ）
};
