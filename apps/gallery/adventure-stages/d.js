/* もふもふ冒険 つないだステージ D「ほしみ屋敷」＝ ステージ 7「とおせんぼ屋敷」→ つなぎ「屋敷の裏の物置場」→ ステージ 5「ほしぞら天文台」。
   つなぎ方は adventure-join.js。後半（天文台）は西へ 96m ずらす（天文台の広場の東の縁が x -87、東の下の台地の東の縁が x -63）。
   つなぎ：屋敷の裏庭（前半のゴールだった所。入口のセーブ地点）の西に、物置場（高さ 0、x -45〜-25・z -2〜12）。西の縁から、天文台の広場の東の縁まで 42m の橋。
     物置場は、天文台のどこからも 18m 以上離す（4 人で積んで投げても届かない）。物置場へは、裏庭からしか来られない（裏庭へは、屋敷の西の引き戸からだけ）。
   物置場のしかけ（前半の板張り＋後半のでんち）：天文台への橋は、橋のたもとのソケットにでんちがある間だけあがる（13m 下に止めておく）。
     でんちは、板張りの戸でふさいだ物置（壁 14m）の中。物置場のたんすを西へ押し、北から南へ押して、戸の板を割る。
   たんすは、橋の手前の敷居（0.5m）で止まり、天文台へは持ちこめない（天文台のソケットのふたは、天文台のたんすで割る）。でんちは、ソケットから出すと橋が沈むので、持って渡れない。
   1 人なら：裏庭から物置場へ → たんすを西へ、物置の戸の前まで押す → 南へ押して戸を割る → でんちをソケットへ → 敷居を跳んで、橋を渡って天文台の広場へ。
   変えたら `node tools/lint-adventure.mjs d` と `node tools/test-adventure.mjs d`（前半 s7.mjs・つなぎ d.mjs・後半 s5.mjs を続けて動かす）で確かめる */
import s7 from './s7.js?v=4.15';
import s5 from './s5.js?v=4.15';
import { join } from '../adventure-join.js?v=4.15';

export default kit => join(kit, {
  name: 'ほしみ屋敷', first: ['s7', s7], second: ['s5', s5], off: [-96, 0],
  // つなぎの中身。座標はステージ全体のもの、番号はつなぎの中だけで数える
  link: ({ B, CP, socket, planks, cell }) => {
    const H = 14;                                                                     // 物置の壁の高さ（屋敷と同じ）
    const wx = (x0, x1, z, top = H, bottom = 0) => B((x0 + x1) / 2, top, z, x1 - x0, 0.6, top - bottom, 1);   // 東西にのびる壁
    const wz = (z0, z1, x) => B(x, H, (z0 + z1) / 2, 0.6, z1 - z0, H, 1);              // 南北にのびる壁
    return {
      boxes: [B(-35, 0, 5, 20, 14, 1, 0),                                             // 0 物置場の床（裏庭の西どなり）
        // 物置（x -45〜-37・z -2〜4.3）。北の戸口（x -42.5〜-39.5）は板張り。戸口の上は 3.5m から壁
        wz(-2, 4.3, -44.7), wz(-2, 4.3, -37.3), wx(-45, -37, -1.7), wx(-45, -42.5, 4), wx(-39.5, -37, 4), wx(-42.5, -39.5, 4, H, 3.5),
        planks(wx(-42.5, -39.5, 4, 3.5)),                                             // 7 物置の戸の板
        B(-44.8, 0.5, 6.5, 0.4, 4.4, 0.5, 1)],                                        // 8 橋の手前の敷居（たんすを止める。人は跳んで越える）
      plates: [socket(-40, 0, 10)],                                                   // 0 橋のたもとのソケット
      movers: [{ b: B(-66, -13, 6.5, 42, 3, 0.5, 4), to: [0, 13, 0], mode: 'hold', on: [0], lamps: true, speed: 6 }],   // 0 天文台への橋（13m 下に止めておく）
      crates: [{ x: -32, y: 0, z: 7, s: 1.4, heavy: true, solo: true },              // 0 物置場のたんす
        cell(-43.4, 0, 1.5)],                                                          // 1 物置の中のでんち
      // 入口のセーブ地点は、裏庭の西の縁（物置場との境 z 1〜9）を全部ふくむ：よけて物置場へ行けない
      cps: [CP(-23, 0, 5, 'とおせんぼ屋敷 → ほしぞら天文台：西の物置の板の戸を、たんすで割ろう。中のでんちを橋のたもとのソケットへ', 4.5)],
      deco: [{ beacon: [-30.5, 0, 9], color: '#ff9f43' }, { beacon: [-38.5, 0, 11.5], color: '#e8ecff' }],   // たんすと、ソケットの目じるし
    };
  },
});
