import s1 from './s1.js?v=4.20';
import s2 from './s2.js?v=4.20';
import { join } from '../adventure-join.js?v=4.20';

export default kit => join(kit, {
  name: 'ひだまり連絡船', first: ['s1', s1], second: ['s2', s2], off: [0, 86],
  // つなぎの中身。座標はステージ全体のもの、番号はつなぎの中だけで数える
  link: ({ B, CP, WP, cell, socket, launcher }) => ({
    boxes: [B(0, 0, 56, 18, 20, 3, 2),                                                // 0 桟橋（N2 の北の縁の 4m 下）
      B(0, 6, 56, 6, 6, 9, 1),                                                        // 1 でんちの柱（高さ 6。N2 から 7m 離す）
      launcher(0, 0.1, 62, [{ on: [0], v: [0, 14, -6] }, { on: [0, 1], v: [0, 12, 21] }])],   // 2 LK：板だけなら柱へ、板とソケットで港へ
    plates: [WP(-5.5, 0, 62, 2), socket(5, 0, 62)],                                  // 0 点 2 つのおもさ板（LK から 3.1m）／1 ソケット
    crates: [{ x: -5.5, y: 0, z: 51, s: 1.4, heavy: true, solo: true },              // 0 重い箱（重さ 2）
      cell(1.5, 6, 54.5)],                                                            // 1 でんち（柱の上）
    cps: [CP(0, 4, 45, 'ひだまり広場 → くるくる港：北の縁から、下の桟橋へおりよう', 7.2),   // N2 の北の縁の、はしからはしまで
      CP(-3, 0, 49, 'ひだまり桟橋：重い箱を点2つの板へ押すと、カタパルトで柱へ。柱のでんちをソケットに入れると、港へ飛べる')],
    deco: [{ beacon: [2.4, 6, 53.6], color: '#ffd84a' }],                             // でんちの目じるし
  }),
});
