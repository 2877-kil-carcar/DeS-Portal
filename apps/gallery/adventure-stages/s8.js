/* もふもふ冒険 ステージ 8「ごとごと操車場」。
   夕方の貨物の操車場。まん中の広い構内（スタート）から、東の倉庫・西の信号小屋・北の行き止まり線へ分かれる。ゴールは、北の 14m 先の島。
   主役は「ポイントつきの貨車」：構内を東西に走る本線の途中に分かれ目があり、北の支線へのびる。信号小屋のレバーで、貨車がどちらへ行くかが決まる。
   東の倉庫：入口は板張り。貨車を本線の東の端まで押しつけると割れる。中の荷台の上に、とても重いコンテナ（おもさ 5）。荷台から押し落として、外へ押し出す。
   西の信号小屋：戸は、外のおもさ板に重さ 5 がのっている間だけあく（コンテナしか届かない：4 人でのっても 4）。中の板を踏んでも、2.5 秒あく（中から出る道）。
   小屋の中のレバーを押しきると、ポイントが支線がわになる。貨車を分かれ目まで戻すと、そこで止まり、北へ押せる。支線の行き止まりに着くと、島への橋があがる。
   壁はどこも 12m（コンテナ・貨車・仲間 3 人を積んでも、てっぺんに手が届かない）。島は構内から 14m（コンテナの上に積んだ仲間から投げられても届かない）。構内の外は空。
   足場や仕掛けの作り方（B・P・CP など）は adventure-world.js の kit を受け取って使う。座標は m、x が東、z が北、y が高さ。
   変えたら `node tools/lint-adventure.mjs 8` と `node tools/test-adventure.mjs 8` で、自動操縦（tools/adventure-bots/s8.mjs）が 1 人で最後まで解けることを確かめる */
export default ({ B, P, WP, CP, lever, cart, railEnd, planks }) => {
  const H = 12;                                                                       // 壁の高さ
  const wx = (x0, x1, z, top = H, bottom = 0) => B((x0 + x1) / 2, top, z, x1 - x0, 0.6, top - bottom, 1);   // 東西にのびる壁（z の線の上）
  const wz = (z0, z1, x, top = H, bottom = 0) => B(x, top, (z0 + z1) / 2, 0.6, z1 - z0, top - bottom, 1);   // 南北にのびる壁（x の線の上）
  return { name: 'ごとごと操車場', sky: ['#3b4a7a', '#ffb38a'], kill: -12,
    boxes: [
      // 床：構内（x -11〜11、z -10〜18）・倉庫（東）・信号小屋（西）・ゴールの島（北。構内から 14m）
      B(0, 0, 4, 22, 28, 1, 1), B(16, 0, 0, 10, 12, 1, 2), B(-16, 0, 0, 10, 12, 1, 1), B(-5, 0, 36, 8, 8, 1, 0),
      // 倉庫の壁。西の入口（z -3.5〜3.5。止まった貨車のわきを、コンテナが通れる幅）は板張り。中に荷台（上面 1）
      wz(-6.3, -3.5, 11), wz(3.5, 6.3, 11), wz(-3.5, 3.5, 11, H, 3.5), planks(wz(-3.5, 3.5, 11, 3.5)),
      wx(10.7, 21.3, -6), wx(10.7, 21.3, 6), wz(-6.3, 6.3, 21), B(18, 1, -1, 4, 6, 1, 2),
      // 信号小屋の壁。東の戸口（z -1.5〜1.5）の下に 0.5m の敷居（コンテナを戸に入れない）。戸口の上は 3.5m から壁
      wz(-6.3, -1.5, -11), wz(1.5, 6.3, -11), wz(-1.5, 1.5, -11, H, 3.5), wz(-1.5, 1.5, -11, 0.5),
      wx(-21.3, -10.7, -6), wx(-21.3, -10.7, 6), wz(-6.3, 6.3, -21),
      // ホーム（支線の東。上がれるが、なにもない）
      B(5, 1, 9, 4, 12, 1, 1)],
    plates: [WP(-3, 0, -1.7, 5), P(-13, 0, 2.5), railEnd(2, 'max'), railEnd(0, 'fork')],
    movers: [
      { b: B(-11, 3.5, 0, 0.4, 3, 3, 4), to: [0, 0, 3.2], mode: 'timed', hold: 2500, on: [0, 1], any: true, lamps: true },   // 0 信号小屋の戸（北の壁の中へ引く）
      { b: B(-5, -13, 25, 3, 14, 0.5, 4), to: [0, 13, 0], mode: 'hold', on: [3], lamps: true, speed: 6 }],                 // 1 島への橋（13m 下に止めておく）
    crates: [cart(-5, 0, 0, 'x', -6, 9.99, { at: 1, to: 14, on: [2] }),             // 0 貨車（本線 x -6〜9.99。x 1 から北の支線へ、z 14 まで）
      { x: 18, y: 1, z: -1.7, s: 1.4, heavy: true, solo: true, mass: 5 },             // 1 コンテナ（倉庫の荷台の上）
      lever(-18, 0, -3, 'x')],                                                        // 2 ポイントのレバー（東へ押しきると、支線がわ）
    cps: [CP(0, 0, -7, '貨車を東へ押して、倉庫の板の入口にぶつけよう'),
      CP(14, 0, 3.5, '荷台のコンテナを押し落として、外のおもさ板まで運ぼう'),
      CP(-7, 0, 6, 'おもさ板にコンテナがのっている間、信号小屋の戸があく。中のレバーで、ポイントが切りかわる'),
      CP(-5, 0, 14, '貨車を北の行き止まりまで押すと、島への橋があがる')],
    goal: { x: -5, y: 0, z: 37 },
    deco: [{ beacon: [-20, 0, 5], color: '#ff5a5a' }, { beacon: [19.5, 1, -3.5], color: '#ffd84a' }, { beacon: [-2, 0, 39], color: '#7ee0a0' }] };
};
