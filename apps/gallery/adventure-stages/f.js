import s11 from './s11.js?v=4.24';
import s12 from './s12.js?v=4.24';
import { join } from '../adventure-join.js?v=4.24';

export default kit => join(kit, {
  name: 'はとば大工事', first: ['s11', s11], second: ['s12', s12], off: [-7, 72],
  // つなぎの中身。座標はステージ全体のもの、番号はつなぎの中だけで数える
  link: ({ B, CP, lever, planks, crane, water }) => {
    const H = 14;                                                                     // 壁の高さ
    const wx = (x0, x1, z, top = H, bottom = 0) => B((x0 + x1) / 2, top, z, x1 - x0, 0.6, top - bottom, 1);   // 東西にのびる壁
    return {
      // 船だまりの床（西に 2.2m×4.8m の水たまり：x -8.1〜-5.9・z 39.2〜44。どこから落ちた木箱も、まん中がフックの通り道 x -7・z 40〜47.6 から 0.5m 以内に浮く幅。
      // まわりの床は、水たまりの底まで厚い）・水たまりの底・木箱の杭・通路
      boxes: [B(-10.05, 0, 40, 3.9, 16, 9, 1), B(3.05, 0, 40, 17.9, 16, 9, 1), B(-7, 0, 35.6, 2.2, 7.2, 9, 1), B(-7, 0, 46, 2.2, 4, 9, 1),
        B(-7, -9, 41.6, 2.2, 4.8, 1, 1), B(-7, -7.5, 40, 1, 1, 1.5, 1), B(-7, 0, 55, 4, 14, 1, 2),
        // 北の壁（東西に 14m ずつはみ出す）。戸口は板張り。戸口の上は 3.5m から壁
        wx(-26, -8.5, 48), wx(-5.5, 26, 48), wx(-8.5, -5.5, 48, H, 3.5), planks(wx(-8.5, -5.5, 48, 3.5)),
        B(-7, 0.5, 49.25, 4, 0.5, 0.5, 1)],                                           // 11 敷居（木箱を止める。人は跳んで越える）
      movers: [water(-7, 41.6, 2.2, 4.8, -6, -9, { rise: 4, handles: [0], up: 4, hold: 30, down: 8 })],   // 0 水たまり（水面 -6 → -2）
      handles: [{ x: -2.5, y: 0, z: 37 }],
      crates: [lever(-1, 0, 41, 'x'), lever(-1, 0, 43, 'x'),                         // 0 クレーンの前後・1 上げ下げ
        { x: -7, y: -7.5, z: 40, s: 1.4, heavy: true }],                              // 2 浮かぶ木箱（杭の上。水があれば浮く）
      // クレーン：x -7、前後 z 40（水たまり）〜 47.6（戸口の板）、フックの底 3m〜-1m（浮いてきた木箱の上面 -1.3 を吊る）
      cranes: [crane(-7, [0, 40, 47.6], [1, 3, -1])],
      // 入口のセーブ地点は、桟橋（前半のゴール）
      cps: [CP(0, 0, 29, 'みなとの工事場 → しおかぜ灯台：水を上げて木箱を浮かべ、クレーンで吊って、北の戸口の板にぶつけよう', 4),
        CP(4, 0, 40, 'フックを下ろして開いてから、水を上げよう')],
      deco: [{ beacon: [-10.5, 0, 33.5], color: '#4fc3ff' }, { beacon: [-4.5, 0, 46.5], color: '#ff9f43' }],
    };
  },
});
